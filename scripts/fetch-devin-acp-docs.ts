/**
 * Refreshes the vendored Devin ACP documentation snapshot under `docs/acp/`.
 *
 * Why a snapshot instead of a live reference: OpenCode references resolve only
 * to a local `path` or a Git `repository`. `docs.devin.ai` is neither, so the
 * load-bearing pages are committed here and refreshed on demand. Every file
 * carries its source URL and fetch date; a snapshot is evidence of what the
 * page said, never proof that it still says it.
 *
 * Usage: bun scripts/fetch-devin-acp-docs.ts [--check]
 *   --check  report drift without writing (exit 1 if a page changed)
 */
