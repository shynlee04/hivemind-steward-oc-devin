const OUT_DIR = join(import.meta.dir, "..", "docs", "acp")

const header = (page: Page, fetchedOn: string): string =>
  [
    "<!--",
    `  source: ${page.url}`,
    `  fetched: ${fetchedOn}`,
    "  generated by: scripts/fetch-devin-acp-docs.ts",
    `  why: ${page.why}`,
    "  Do not edit by hand. Re-run the script; hand edits are overwritten.",
    "-->",
    "",
  ].join("\n")

const main = async (): Promise<number> => {
  const check = process.argv.includes("--check")
  await mkdir(OUT_DIR, { recursive: true })
  const fetchedOn = new Date().toISOString().slice(0, 10)
  const drifted: string[] = []

  for (const page of PAGES) {
    const response = await fetch(page.url)
    if (!response.ok) {
      console.error(`FAIL ${page.file}: ${response.status} ${page.url}`)
      return 1
    }
    const body = (await response.text()).trimEnd()
    const target = join(OUT_DIR, page.file)
    const next = header(page, fetchedOn) + body + "\n"

    const previous = await Bun.file(target).text().catch(() => "")
    // Compare bodies only: a refetch on a different day must not read as drift.
    const previousBody = previous.slice(previous.indexOf("-->") + 3).trim()
    if (previousBody !== body.trim()) drifted.push(page.file)

    if (check) {
      console.log(`${drifted.includes(page.file) ? "DRIFT" : "  ok "} ${page.file} (${body.length} B)`)
    } else {
      await Bun.write(target, next)
      console.log(`wrote ${page.file} (${next.length} B)`)
    }
  }

  if (check && drifted.length > 0) {
    console.error(`\n${drifted.length} page(s) drifted: ${drifted.join(", ")}`)
    console.error("Re-run without --check to refresh, then re-verify the wire inventory in .planning/.")
    return 1
  }
  return 0
}

process.exit(await main())